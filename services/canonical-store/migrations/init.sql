-- ============================================================
-- Canonical events table
-- ============================================================
CREATE TABLE IF NOT EXISTS canonical_events (
  hazard_id     TEXT PRIMARY KEY,           -- UUID generated by Aggregator on first insert
  source        TEXT NOT NULL,              -- 'BMKG' | 'PVMBG'
  source_ref_id TEXT NOT NULL,              -- original event_id / report_id
  hazard_type   TEXT NOT NULL,              -- 'SEISMIC' | 'VOLCANIC'
  severity      TEXT NOT NULL,              -- 'NORMAL' | 'WASPADA' | 'SIAGA' | 'AWAS'
  area_name     TEXT NOT NULL,
  latitude      DOUBLE PRECISION NOT NULL,
  longitude     DOUBLE PRECISION NOT NULL,
  occurred_at   TIMESTAMPTZ NOT NULL,
  ingested_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  version       BIGINT NOT NULL DEFAULT 1,
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  sources       JSONB NOT NULL DEFAULT '{}',  -- {"bmkg": {...}, "pvmbg": {...}} raw payloads
  attributes    JSONB NOT NULL DEFAULT '{}'   -- merged dynamic fields incl. confidence_level
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_canonical_events_source_ref
  ON canonical_events (source, source_ref_id);

CREATE INDEX IF NOT EXISTS idx_canonical_events_gin_attrs
  ON canonical_events USING GIN (attributes jsonb_path_ops);

CREATE INDEX IF NOT EXISTS idx_canonical_events_type_time
  ON canonical_events (hazard_type, occurred_at DESC);

-- ============================================================
-- Transactional outbox table
-- ============================================================
CREATE TABLE IF NOT EXISTS outbox (
  id           BIGSERIAL PRIMARY KEY,
  event_key    TEXT UNIQUE NOT NULL,   -- hazard_id:version (idempotency key)
  payload      JSONB NOT NULL,
  published_at TIMESTAMPTZ              -- NULL = not yet published
);

CREATE INDEX IF NOT EXISTS idx_outbox_unpublished
  ON outbox (id) WHERE published_at IS NULL;
